/**
 * 展示用文本压缩的单位测试：大数字缩成 M / k，长路径缩成末两级。
 *
 * 为什么这组用例值得钉：两个函数的结果都直接进状态栏和欢迎页。它们不会崩溃，错了
 * 只会表现成「同一个数字在两个地方长得不一样」或者「路径短得看不出是哪个项目」——
 * 排查时没人会先怀疑格式化函数。所以这里钉的是**阈值与舍入**，不是「有没有输出」。
 *
 * @module dsc/core/text-format.spec
 */
import { expect, test } from 'vitest'
import { compactTokens, shortCwd } from './text-format.js'

// ── 数字缩写 ────────────────────────────────────────────────────────────────

test('999 原样输出，不加 k', () => {
  // 阈值下界：999 加 k 会变成 '1.0k'，而实际没到一千，用户会以为用量翻倍。
  expect(compactTokens(999)).toBe('999')
})

test('1000 整缩成 1.0k，小数位固定一位', () => {
  // 边界正好落在一千：固定一位小数是为了让 '1.0k' 与 '1.2k' 宽度一致，
  // 状态栏数字不跳来跳去。
  expect(compactTokens(1000)).toBe('1.0k')
})

test('1234 缩成 1.2k（保留一位，不四舍五入成 1k）', () => {
  expect(compactTokens(1234)).toBe('1.2k')
})

test('999999 仍在 k 档，舍入后显示 1000.0k', () => {
  // 这是阈值与舍入的交界：999999 < 1000000，进不了 M 档，但 /1000 之后 toFixed(1)
  // 会进到 '1000.0'。这条钉住的是「档位由原值判、不看舍入后的结果」，谁把它改成
  // 「先舍入再判档」这里立刻红。
  expect(compactTokens(999_999)).toBe('1000.0k')
})

test('1000000 起改走 M 档', () => {
  expect(compactTokens(1_000_000)).toBe('1.0M')
})

test('1234567 缩成 1.2M', () => {
  expect(compactTokens(1_234_567)).toBe('1.2M')
})

test('0 原样给 0，不缩成 0.0k', () => {
  // 空会话的 token 用量就是 0；'0.0k' 会让状态栏看起来像「有数据但很小」。
  expect(compactTokens(0)).toBe('0')
})

test('负数原样输出，不套 k / M', () => {
  // 差值为负时（缓存命中数大于用量之类）会走到这里；负数没有「缩写」的语义，
  // 原样显示才能看出确实为负。
  expect(compactTokens(-1500)).toBe('-1500')
})

// ── 路径缩写 ────────────────────────────────────────────────────────────────

test('四级路径缩成末两级并加省略号', () => {
  // '/a/b/c/d' → '…c/d'：省掉的是 '/a/b' 这一段。注意模块注释写的是 '…/c/d'，
  // 实现拼出来没有中间那个斜杠——这里钉当前输出，差异已在交付报告里登记。
  expect(shortCwd('/a/b/c/d')).toBe('…c/d')
})

test('正好两级时原样返回，不加省略号', () => {
  // 两级以内缩了反而看不懂（'…/b' 不如 '/a/b'）；这条是「短路径保持原样」的下界。
  expect(shortCwd('/a/b')).toBe('/a/b')
})

test('一级路径原样返回', () => {
  expect(shortCwd('proj')).toBe('proj')
})

test('相对路径同样只留末两级', () => {
  // 相对路径没有前导斜杠，切分后同样按段数判断，不能因为不以 '/' 开头就整段返回。
  expect(shortCwd('a/b/c')).toBe('…b/c')
})

test('Windows 反斜杠路径同样缩成末两级，连接符统一成斜杠', () => {
  // 桌面端在 Windows 上传进来的 cwd 是 `C:\work\proj\src\x.ts`。按 `[\\/]` 切分后
  // 段数是 5，缩完是 '…src/x.ts'——盘符与中间目录一起被省掉。
  expect(shortCwd('C:\\work\\proj\\src\\x.ts')).toBe('…src/x.ts')
})

test('末尾带分隔符时不计空段', () => {
  // '/a/b/c/' 切出来会多一个空串；不过滤的话段数算成 4 会误判成「需要缩写」。
  expect(shortCwd('/a/b/c/')).toBe('…b/c')
})

test('连续分隔符不计空段', () => {
  // '/a//b/c' 中间的空段同理：过滤后是 3 段，缩成 '…b/c'。
  expect(shortCwd('/a//b/c')).toBe('…b/c')
})

test('空串原样返回空串', () => {
  // 没有 cwd 时（比如还没打开工作区）不能返回 '…'——那会被界面当成一个真路径显示出来。
  expect(shortCwd('')).toBe('')
})
